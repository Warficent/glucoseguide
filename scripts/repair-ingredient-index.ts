// Retries any recipes whose ingredient list came back empty (TheMealDB rate
// limiting) and rewrites src/lib/ingredient-index.generated.ts in place.
//   bun run scripts/repair-ingredient-index.ts
import { FOODS } from "../src/lib/data";
import { findMealForFood } from "../src/lib/mealdb";
import { INGREDIENT_INDEX } from "../src/lib/ingredient-index.generated";
import { writeFileSync } from "node:fs";

const STOPWORDS = new Set([
  "fresh", "dried", "chopped", "sliced", "diced", "minced", "grated",
  "large", "small", "medium", "whole", "ground", "cooked", "raw", "boneless",
  "skinless", "peeled", "crushed", "finely", "roughly", "extra", "virgin",
  "of", "the", "and", "or", "for", "to", "taste", "optional",
]);

function normalizeIngredient(raw: string): string {
  let s = raw.toLowerCase().trim();
  s = s.replace(/\(.*?\)/g, " ").replace(/[^a-z\s-]/g, " ");
  const words = s.split(/\s+/).filter((w) => w && !STOPWORDS.has(w));
  let name = words.join(" ").trim();
  if (name.endsWith("ies") && name.length > 4) name = name.slice(0, -3) + "y";
  else if (name.endsWith("oes")) name = name.slice(0, -2);
  else if (name.endsWith("s") && !name.endsWith("ss")) name = name.slice(0, -1);
  return name.trim();
}

const CATEGORIES: Record<string, string[]> = {
  Produce: ["tomato","onion","garlic","potato","carrot","celery","pepper","bell pepper","spinach","lettuce","cucumber","broccoli","mushroom","zucchini","eggplant","apple","banana","lemon","lime","orange","strawberry","blueberry","raspberry","avocado","ginger","chilli","chili","parsley","coriander","cilantro","basil","mint","thyme","rosemary","kale","cabbage","corn","peas","leek","shallot","scallion","spring onion","cauliflower"],
  Dairy: ["milk","butter","cheese","cream","yogurt","yoghurt","parmesan","cheddar","mozzarella","feta","ricotta","sour cream","cream cheese","egg"],
  Protein: ["chicken","beef","pork","lamb","bacon","sausage","ham","turkey","fish","salmon","tuna","cod","shrimp","prawn","crab","lobster","tofu","chickpea","lentil","bean","black bean"],
  Pantry: ["flour","sugar","salt","pepper","olive oil","oil","vinegar","soy sauce","rice","pasta","bread","stock","broth","tomato paste","tomato sauce","honey","syrup","yeast","baking powder","baking soda","cornstarch","vanilla","cocoa","chocolate","cinnamon","cumin","paprika","nutmeg","oregano","bay leaf","mustard","mayonnaise","ketchup","wine","water"],
};

async function fetchNames(search: string): Promise<string[]> {
  const meal = await findMealForFood(search);
  if (!meal) return [];
  return Array.from(
    new Set(
      meal.ingredients
        .map((i) => normalizeIngredient(i.name))
        .filter((n) => n.length > 1),
    ),
  );
}

async function main() {
  const index: Record<string, string[]> = { ...INGREDIENT_INDEX };
  const missing = FOODS.filter((f) => !(index[f.id]?.length));
  console.error(`${missing.length} recipes need repair`);

  for (let pass = 1; pass <= 4 && missing.length; pass++) {
    let fixed = 0;
    for (const food of FOODS) {
      if (index[food.id]?.length) continue;
      try {
        const names = await fetchNames(food.mealSearch);
        if (names.length) {
          index[food.id] = names;
          fixed++;
        }
      } catch {
        /* retry next pass */
      }
      await new Promise((r) => setTimeout(r, 350));
    }
    const left = FOODS.filter((f) => !(index[f.id]?.length)).length;
    console.error(`pass ${pass}: fixed ${fixed}, ${left} still empty`);
    if (!left) break;
    await new Promise((r) => setTimeout(r, 3000));
  }

  const all = new Set<string>();
  for (const names of Object.values(index)) names.forEach((n) => all.add(n));
  const sortedAll = Array.from(all).sort();
  const categorized: Record<string, string[]> = {};
  for (const [cat, seeds] of Object.entries(CATEGORIES)) {
    categorized[cat] = sortedAll.filter((ing) =>
      seeds.some((s) => ing === s || ing.includes(s)),
    );
  }

  const body = `// AUTO-GENERATED by scripts/build-ingredient-index.ts. Do not edit by hand.
export const INGREDIENT_INDEX: Record<string, string[]> = ${JSON.stringify(index, null, 2)};

export const ALL_INGREDIENTS: string[] = ${JSON.stringify(sortedAll, null, 2)};

export const INGREDIENT_CATEGORIES: Record<string, string[]> = ${JSON.stringify(categorized, null, 2)};
`;
  writeFileSync("src/lib/ingredient-index.generated.ts", body);
  const empty = FOODS.filter((f) => !(index[f.id]?.length)).map((f) => f.id);
  console.error(`Done. ${empty.length} still empty: ${empty.join(", ")}`);
}

main();
