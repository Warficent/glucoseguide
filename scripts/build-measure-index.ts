// One-time script: fetches every recipe from TheMealDB for FOODS and writes
// src/lib/measures.generated.ts, mapping each recipe id to its ingredient
// names *with* their printed measures. The glycemic model needs the measures
// to weight each carbohydrate source by how much of it the recipe uses
// (Jenkins 2002 mixed-meal model).
//   bun run scripts/build-measure-index.ts
import { FOODS } from "../src/lib/data";
import { findMealForFood } from "../src/lib/mealdb";
import { writeFileSync } from "node:fs";

const STOPWORDS = new Set([
  "fresh", "dried", "chopped", "sliced", "diced", "minced", "grated",
  "large", "small", "medium", "whole", "ground", "cooked", "raw", "boneless",
  "skinless", "peeled", "crushed", "finely", "roughly", "extra", "virgin",
  "of", "the", "and", "or", "for", "to", "taste", "optional",
]);

function normalizeIngredient(raw: string): string {
  let s = raw.toLowerCase().trim();
  s = s.replace(/\(.*?\)/g, " ").replace(/[^a-z\s-]/g, " ");
  const words = s.split(/\s+/).filter((w) => w && !STOPWORDS.has(w));
  let name = words.join(" ").trim();
  if (name.endsWith("ies") && name.length > 4) name = name.slice(0, -3) + "y";
  else if (name.endsWith("oes")) name = name.slice(0, -2);
  else if (name.endsWith("s") && !name.endsWith("ss")) name = name.slice(0, -1);
  return name.trim();
}

async function main() {
  const index: Record<string, { name: string; measure: string }[]> = {};
  let done = 0;
  for (const food of FOODS) {
    try {
      const meal = await findMealForFood(food.mealSearch);
      index[food.id] = meal
        ? meal.ingredients
            .map((i) => ({
              name: normalizeIngredient(i.name),
              measure: (i.measure ?? "").trim(),
            }))
            .filter((i) => i.name.length > 1)
        : [];
    } catch {
      index[food.id] = [];
    }
    done++;
    if (done % 20 === 0) console.error(`${done}/${FOODS.length}`);
    await new Promise((r) => setTimeout(r, 60));
  }

  const body = `// AUTO-GENERATED by scripts/build-measure-index.ts. Do not edit by hand.
export type MeasuredIngredient = { name: string; measure: string };

export const MEASURE_INDEX: Record<string, MeasuredIngredient[]> = ${JSON.stringify(index, null, 2)};
`;
  writeFileSync("src/lib/measures.generated.ts", body);
  console.error(`Wrote measures for ${FOODS.length} recipes.`);
}

main();
