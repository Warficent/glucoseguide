// Checks every recipe's TheMealDB YouTube link and records the ones that are
// private / removed / region-blocked, so the app can hide the "Watch" button.
//   bun run scripts/check-youtube-links.ts
import { FOODS } from "../src/lib/data";
import { findMealForFood } from "../src/lib/mealdb";
import { writeFileSync } from "node:fs";

function videoId(url: string): string | null {
  const m = url.match(/[?&]v=([A-Za-z0-9_-]{6,})/) || url.match(/youtu\.be\/([A-Za-z0-9_-]{6,})/);
  return m ? m[1] : null;
}

async function isPlayable(id: string): Promise<boolean> {
  try {
    const res = await fetch(
      `https://www.youtube.com/oembed?url=${encodeURIComponent(
        `https://www.youtube.com/watch?v=${id}`,
      )}&format=json`,
    );
    return res.ok;
  } catch {
    return false;
  }
}

async function main() {
  const bad: string[] = [];
  let checked = 0;
  for (const food of FOODS) {
    try {
      const meal = await findMealForFood(food.mealSearch);
      const url = meal?.strYoutube;
      if (url) {
        const id = videoId(url);
        if (!id || !(await isPlayable(id))) bad.push(id ?? url);
      }
    } catch {
      /* ignore */
    }
    checked++;
    if (checked % 20 === 0) console.error(`${checked}/${FOODS.length} (${bad.length} bad)`);
    await new Promise((r) => setTimeout(r, 40));
  }
  writeFileSync(
    "src/lib/youtube-blocklist.generated.ts",
    `// AUTO-GENERATED by scripts/check-youtube-links.ts. Do not edit by hand.
// YouTube video IDs that are private, removed, or otherwise unplayable.
export const BLOCKED_YOUTUBE_IDS: string[] = ${JSON.stringify(bad.sort(), null, 2)};

export function isYoutubePlayable(url: string | null | undefined): boolean {
  if (!url) return false;
  const m = url.match(/[?&]v=([A-Za-z0-9_-]{6,})/) || url.match(/youtu\\.be\\/([A-Za-z0-9_-]{6,})/);
  const id = m ? m[1] : null;
  if (!id) return false;
  return !BLOCKED_YOUTUBE_IDS.includes(id);
}
`,
  );
  console.error(`Done. ${bad.length} unplayable of ${FOODS.length}.`);
}

main();
