export type EaseLevel = "Easy" | "Medium" | "Involved";
export const EASE_LEVELS: EaseLevel[] = ["Easy", "Medium", "Involved"];


export type Zone = "severe-low" | "low" | "in-range" | "high" | "severe-high";

export function zoneFor(mgdl: number): Zone {
  if (mgdl < 54) return "severe-low";
  if (mgdl < 70) return "low";
  if (mgdl <= 180) return "in-range";
  if (mgdl <= 400) return "high";
  return "severe-high";
}

export function zoneLabel(z: Zone): string {
  return {
    "severe-low": "Severe low",
    low: "Low",
    "in-range": "In range",
    high: "High",
    "severe-high": "Severe high",
  }[z];
}

export function zoneColor(z: Zone): string {
  return {
    "severe-low": "#7f1d1d",
    low: "#dc2626",
    "in-range": "#16a34a",
    high: "#6C2BD9",
    "severe-high": "#7f1d1d",
  }[z];
}

export function suggestFoods(
  mgdl: number,
  liked: string[],
  ease?: EaseLevel | null,
): Food[] {
  const z = zoneFor(mgdl);
  let pool: Food[];
  if (z === "severe-low" || z === "low") {
    pool = [...FOODS].sort((a, b) => a.impact - b.impact);
  } else if (z === "high" || z === "severe-high") {
    pool = [...FOODS].sort((a, b) => b.impact - a.impact);
  } else {
    pool = FOODS.filter((f) => f.impact >= 4 && f.impact <= 8);
  }
  if (ease) pool = pool.filter((f) => easeLabel(f.id) === ease);
  // Keep the zone-appropriate front of the pool, then prefer the easiest to make.
  const shortlist = pool.slice(0, 24);
  const ranked = [...shortlist].sort((a, b) => {
    const la = liked.includes(a.id) ? 0 : 1;
    const lb = liked.includes(b.id) ? 0 : 1;
    if (la !== lb) return la - lb;
    const ea = easeForFood(a.id);
    const eb = easeForFood(b.id);
    if (ea !== eb) return ea - eb;
    return a.name.localeCompare(b.name);
  });
  return ranked.slice(0, 4);
}


import { INGREDIENT_INDEX } from "./ingredient-index.generated";

export type IngredientMode = "any" | "only";

export type IngredientMatch = {
  food: Food;
  matched: number;
  total: number;
};

export function ingredientsForFood(id: string): string[] {
  return INGREDIENT_INDEX[id] ?? [];
}

// Ease of making a recipe, approximated by how many ingredients it needs.
// Lower is easier. Unknown recipes sort last.
export function easeForFood(id: string): number {
  const n = ingredientsForFood(id).length;
  return n === 0 ? 99 : n;
}

export function easeLabel(id: string): string | undefined {
  const n = ingredientsForFood(id).length;
  if (n === 0) return undefined;
  if (n <= 6) return "Easy";
  if (n <= 10) return "Medium";
  return "Involved";
}


// Fuzzy match: an ingredient in the recipe counts as "have" if any selected
// pantry item is a substring match (either direction). Handles "tomato" vs
// "cherry tomato", "chicken" vs "chicken breast", etc.
function hasIngredient(recipeIng: string, pantry: Set<string>): boolean {
  if (pantry.has(recipeIng)) return true;
  for (const p of pantry) {
    if (recipeIng.includes(p) || p.includes(recipeIng)) return true;
  }
  return false;
}

export function filterFoodsByIngredients(
  foods: Food[],
  selected: string[],
  mode: IngredientMode,
): IngredientMatch[] {
  if (selected.length === 0) {
    return foods
      .map((f) => ({ food: f, matched: 0, total: ingredientsForFood(f.id).length }))
      .sort((a, b) => {
        const ea = easeForFood(a.food.id);
        const eb = easeForFood(b.food.id);
        if (ea !== eb) return ea - eb;
        return a.food.name.localeCompare(b.food.name);
      });
  }

  const pantry = new Set(selected.map((s) => s.toLowerCase().trim()));
  const results: IngredientMatch[] = [];
  for (const food of foods) {
    const ings = ingredientsForFood(food.id);
    if (ings.length === 0) continue;
    const matched = ings.filter((i) => hasIngredient(i, pantry)).length;
    if (mode === "any") {
      if (matched > 0) results.push({ food, matched, total: ings.length });
    } else {
      // "only": every recipe ingredient must be covered by pantry
      if (matched === ings.length) results.push({ food, matched, total: ings.length });
    }
  }
  results.sort((a, b) => {
    const ra = a.matched / a.total;
    const rb = b.matched / b.total;
    if (rb !== ra) return rb - ra;
    const ea = easeForFood(a.food.id);
    const eb = easeForFood(b.food.id);
    if (ea !== eb) return ea - eb;
    return a.food.name.localeCompare(b.food.name);
  });

  return results;
}

